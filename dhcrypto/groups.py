"""
groups.py — Bộ tham số (q, α) dùng cho Diffie–Hellman.

1) Bộ số nhỏ để minh hoạ / tính tay (ký hiệu theo slide: q, α, x_A, x_B).
2) Các nhóm chuẩn (số nguyên tố an toàn) công bố trong RFC 2409, RFC 3526
   (nhóm MODP) và RFC 7919 (nhóm FFDHE). Các hằng số dưới đây được nhóm tự
   TÍNH LẠI từ công thức trong RFC bằng script tools/derive_rfc_groups.py, và
   được đối chiếu với OpenSSL trong bộ kiểm thử (tests/run_tests.py).

Với các nhóm RFC: q = 2r + 1 (r nguyên tố) và α = 2 sinh ra nhóm con cấp r.
Dùng nhóm con cấp nguyên tố r là cách làm chuẩn: mọi khoá công khai hợp lệ y
phải thoả y^r ≡ 1 (mod q), giúp phát hiện tấn công nhóm con nhỏ.
"""
from dataclasses import dataclass, field
from typing import Optional


@dataclass(frozen=True)
class DHGroup:
    name: str                    # tên nhóm
    q: int                       # số nguyên tố modulo (slide gọi là q)
    alpha: int                   # phần tử sinh α
    order: Optional[int] = None  # cấp của α (r) nếu đã biết; None = q - 1
    source: str = ""             # nguồn gốc tham số
    sample_xA: Optional[int] = None   # khoá riêng mẫu (chỉ cho ví dụ nhỏ)
    sample_xB: Optional[int] = None

    @property
    def bits(self) -> int:
        return self.q.bit_length()

    @property
    def subgroup_order(self) -> int:
        return self.order if self.order else self.q - 1


